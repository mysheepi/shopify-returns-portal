INSERT INTO sku_config (sku, product_name, return_window_days, is_active, updated_at)
SELECT sku, product_name, return_window_days, TRUE, now() FROM final_skus
ON CONFLICT (sku) DO UPDATE
SET product_name = CASE
        WHEN sku_config.product_name IS NULL OR sku_config.product_name = ''
        THEN EXCLUDED.product_name
        ELSE sku_config.product_name
    END,
    updated_at = CASE
        WHEN sku_config.product_name IS NULL OR sku_config.product_name = ''
        THEN now()
        ELSE sku_config.updated_at
    END;
